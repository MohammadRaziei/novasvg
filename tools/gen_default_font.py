#!/usr/bin/env python3
"""Regenerate include/novasvg/detail/default_font.h from data/fonts/DejaVuSans*.ttf.

The header embeds a Latin subset of DejaVu Sans -- regular, bold, oblique (italic) and bold oblique --
as base64, used by novasvg only as the last-resort fallback when the machine has no font for a request
(see FontFaceCache::getFontFace), which picks the face matching the requested weight and style. Kerning
(GPOS and the legacy kern table) and the ligature substitutions are kept so that text lays out exactly
like the full font; test_novasvg_embedded_font checks that.

    python tools/gen_default_font.py            # needs: pip install fonttools

The base64 is split into literals well under MSVC's per-literal limit (16380 characters).
"""
import base64
import zlib
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "data" / "fonts"
# (C++ array name, source file); the regular face keeps the name it always had.
FACES = [
    ("kEmbeddedFontZlibBase64", "DejaVuSans.ttf"),
    ("kEmbeddedFontBoldZlibBase64", "DejaVuSans-Bold.ttf"),
    ("kEmbeddedFontItalicZlibBase64", "DejaVuSans-Oblique.ttf"),
    ("kEmbeddedFontBoldItalicZlibBase64", "DejaVuSans-BoldOblique.ttf"),
]
TARGET = ROOT / "include" / "novasvg" / "detail" / "default_font.h"
CHUNK = 12000

# Basic Latin, Latin-1 Supplement, the punctuation/symbols text commonly carries, and the f-ligature
# presentation forms U+FB00..FB04 (novasvg applies the font's fi/fl/ff/ffi/ffl ligatures through them).
CODEPOINTS = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC, 0x2122]
    + list(range(0xFB00, 0xFB05))
)
FEATURES = ["kern", "liga", "calt", "ccmp", "locl", "mark", "mkmk", "clig"]


def subset_font(source):
    options = subset.Options()
    options.layout_features = FEATURES
    options.legacy_kern = True
    options.hinting = False
    options.notdef_outline = True
    options.name_IDs = ["*"]
    font = TTFont(str(source), recalcTimestamp=False)  # keep head.modified: the output must not depend on the clock
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=CODEPOINTS)
    subsetter.subset(font)
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


LINE = 100  # characters of base64 per source line


def lines_of(data):
    """zlib, then base64, cut into short source lines (one string literal each, far below MSVC's limit)."""
    encoded = base64.b64encode(zlib.compress(data, 9)).decode("ascii")
    return [encoded[i:i + LINE] for i in range(0, len(encoded), LINE)]


def render(faces):
    lines = [
        "// Generated by tools/gen_default_font.py from data/fonts/DejaVuSans*.ttf -- do not edit.",
        "//",
        "// Latin subsets of DejaVu Sans -- regular, bold, oblique (italic) and bold oblique -- kerning and",
        "// ligatures kept. Each is zlib-compressed and then base64-encoded (decoded with the base64 and zlib",
        "// code the library already has for @font-face and PNG). They are novasvg's last-resort fallback",
        "// fonts, used only when a request finds no other font; the face matching the requested weight and",
        "// style is decoded on first use. DejaVu fonts are free software: see data/fonts/LICENSE-DejaVu.txt.",
        "#pragma once",
        "",
        "namespace novasvg {",
        "namespace detail {",
    ]
    for (name, src), data in zip(FACES, faces):
        encoded = lines_of(data)
        lines += ["", "// %s: %d bytes of TrueType, %d characters of base64" % (src, len(data), sum(len(x) for x in encoded)),
                  "inline constexpr const char* const %s[] = {" % name]
        lines += ['    "%s",' % x for x in encoded]
        lines += ["    nullptr,", "};"]
    lines += ["", "} // namespace detail", "} // namespace novasvg", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    faces = [subset_font(FONTS / src) for _, src in FACES]
    TARGET.write_text(render(faces), newline="\n")
    print("wrote %s (%s font bytes)" % (TARGET.relative_to(ROOT), "+".join(str(len(d)) for d in faces)))
    sys.exit(0)
